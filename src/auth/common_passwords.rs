/// Whether `password` is on the refusal list, ignoring case.
pub fn is_common(password: &str) -> bool {
    let lowered = password.trim().to_lowercase();
    COMMON.contains(&lowered.as_str())
}

#[cfg(test)]
mod tests {
    use super::{COMMON, is_common};

    #[test]
    fn the_list_is_lowercase_and_within_the_length_rule() {
        for entry in COMMON {
            assert_eq!(*entry, entry.to_lowercase(), "{entry}");
            assert!(
                entry.chars().count() >= 8,
                "{entry} would fail the length rule anyway"
            );
        }
    }

    #[test]
    fn common_passwords_are_refused_in_any_case_and_uncommon_ones_pass() {
        assert!(is_common("Password123"));
        assert!(is_common("  QWERTYUIOP "));
        assert!(!is_common("correct horse battery staple"));
        assert!(!is_common("Zoë-rides-bikes-2026"));
    }
}
